#Python allows you to assign values to multiple variables in one line:
x, y, z = "Orange", "Banana", "Cherry"
print(x)
print(y)
print(z)
# We should make sure that the number of variables matches the number of values, or else we will get an error.

# One value to Multiple Variables
# We can assign the same value to mutliple variables in one line:
a = b = c = "Apple"
